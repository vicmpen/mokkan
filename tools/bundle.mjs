#!/usr/bin/env node
// Builds the Claude Code plugin's CLI: one self-contained ESM file, committed at claude-plugin/scripts/mokkan.mjs.
// The plugin is installed by copying claude-plugin/ out of git, so the CLI must be committed there and must not need
// node_modules. `mokkan statusline` also copies this single file to a stable path, which only works for one file.
//
//   node tools/bundle.mjs           write the bundle
//   node tools/bundle.mjs --check   exit 1 if the committed bundle differs from a fresh build (CI, prepublishOnly)
import { build } from 'esbuild';
import { chmodSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const BUNDLE_PATH = path.join(ROOT, 'claude-plugin', 'scripts', 'mokkan.mjs');

const BANNER = '// Generated by `npm run bundle` from src/ (tools/bundle.mjs). Do not edit; change src/ and rebuild.';

/** Builds the bundle in memory and returns its text. Deterministic for a given src/ and esbuild version. */
export async function buildBundle() {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: ['src/cli.ts'],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    write: false,
    outfile: BUNDLE_PATH,
    banner: { js: BANNER },
    legalComments: 'none',
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

async function run() {
  const fresh = await buildBundle();
  if (process.argv.includes('--check')) {
    let committed = '';
    try { committed = readFileSync(BUNDLE_PATH, 'utf8'); } catch { /* missing counts as stale */ }
    if (committed !== fresh) {
      console.error(`${path.relative(ROOT, BUNDLE_PATH)} is stale: run \`npm run bundle\` and commit the result.`);
      process.exit(1);
    }
    console.log(`${path.relative(ROOT, BUNDLE_PATH)} is up to date.`);
    return;
  }
  writeFileSync(BUNDLE_PATH, fresh);
  chmodSync(BUNDLE_PATH, 0o755);
  console.log(`Wrote ${path.relative(ROOT, BUNDLE_PATH)} (${Buffer.byteLength(fresh)} bytes).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await run();
