import { homedir } from 'node:os';
import path from 'node:path';
import { notifyStateDir } from '../../credentials.js';
import type { OscMode } from '../config.js';

/** What `init.<shell>` bakes in: the absolute node and cli.js paths, the CLI version and the settings. */
export interface SnippetOptions {
  node: string;
  cli: string;
  version: string;
  /** Seconds between polls; a shell starts `notify poll` only when the stamp is at least this old. */
  interval: number;
  osc: OscMode;
}

export type ShellName = 'zsh' | 'bash' | 'fish';

/**
 * A shell the prompt hook supports. The hook itself lives in the generated `init.<name>` (in the notify state
 * directory, regenerated by setup, on/off and poll); the user's rc file only sources it.
 * - `rc-block`: `rcFile` gets a marked block holding `rcLine()`.
 * - `drop-in`: `rcFile` is a file of its own (fish conf.d) whose whole content is `rcLine()`.
 */
export interface NotifyShell {
  name: ShellName;
  installStyle: 'rc-block' | 'drop-in';
  rcFile(env: NodeJS.ProcessEnv, platform: NodeJS.Platform): string;
  initFile(env: NodeJS.ProcessEnv): string;
  snippet(opts: SnippetOptions): string;
  rcLine(): string;
}

export function home(env: NodeJS.ProcessEnv): string {
  return env.HOME && env.HOME !== '' ? env.HOME : homedir();
}

export function xdgConfigHome(env: NodeJS.ProcessEnv): string {
  return env.XDG_CONFIG_HOME && env.XDG_CONFIG_HOME !== '' ? env.XDG_CONFIG_HOME : path.join(home(env), '.config');
}

export function initFileFor(env: NodeJS.ProcessEnv, name: ShellName): string {
  return path.join(notifyStateDir(env), `init.${name}`);
}

/** A POSIX shell word: single quotes, with each `'` written as `'\''`. */
export function shQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** A fish word: single quotes, where only `\` and `'` are escaped. */
export function fishQuote(s: string): string {
  return `'${s.replace(/[\\']/g, (c) => `\\${c}`)}'`;
}

/** The first line of every `init.<shell>`; `ensureInitScripts` regenerates a file whose content differs. */
export function headerLine(opts: SnippetOptions): string {
  return `# generated by mokkan ${opts.version} (interval ${opts.interval}, osc ${opts.osc}); regenerate with: mokkan notify setup`;
}

/** Rejects values that would break the generated script (a version is baked into a comment, interval into arithmetic). */
export function checkOptions(opts: SnippetOptions): void {
  if (!/^[0-9A-Za-z.+-]+$/.test(opts.version)) throw new Error(`invalid version for the shell snippet: ${JSON.stringify(opts.version)}`);
  if (!Number.isInteger(opts.interval) || opts.interval < 1) throw new Error(`invalid interval for the shell snippet: ${opts.interval}`);
  for (const p of [opts.node, opts.cli]) {
    if (!path.isAbsolute(p) || /[\0\n\r]/.test(p)) throw new Error(`the shell snippet needs an absolute path without newlines: ${JSON.stringify(p)}`);
  }
}

/**
 * printf format strings (as shell source text, to go inside single quotes) for each OSC notification sequence, plain
 * and wrapped in tmux's DCS passthrough (every ESC doubled). `%s` is the reminder text, passed as an argument.
 * `bs` is how a literal backslash is written in the format string for this shell's quoting.
 */
export function oscFormats(bs: string): Record<'9' | '777' | '99', { plain: string; tmux: string }> {
  const E = '\\033';
  const BEL = '\\007';
  const ST = `${E}${bs}`;
  const seqs = { '9': `${E}]9;%s${BEL}`, '777': `${E}]777;notify;mokkan;%s${BEL}`, '99': `${E}]99;;%s${ST}` };
  const wrap = (seq: string): string => `${E}Ptmux;${seq.split(E).join(E + E)}${ST}`;
  return {
    '9': { plain: seqs['9'], tmux: wrap(seqs['9']) },
    '777': { plain: seqs['777'], tmux: wrap(seqs['777']) },
    '99': { plain: seqs['99'], tmux: wrap(seqs['99']) },
  };
}

/** Which OSC modes the generated script may emit: one fixed mode, or all three for `auto` (chosen at print time). */
export function oscModesFor(osc: OscMode): Array<'9' | '777' | '99'> {
  return osc === 'off' ? [] : osc === 'auto' ? ['99', '777', '9'] : [osc];
}
